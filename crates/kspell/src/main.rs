const DATA_NOTE: &[&str] = &[
    "Kannada spelling lexicon. Stems from Alar by V. Krishna (https://alar.ink),",
    "licensed under the Open Database License 1.0 (https://opendatacommons.org/licenses/odbl/1-0/).",
    "This derived database is also licensed under the ODbL 1.0. See DATA-LICENSE.md.",
];

const AFFIX_NOTE: &[&str] = &[
    "Kannada affix rules, generated by kspell from the kannada-morph paradigms. MIT License.",
    "Contains no Alar data. The matching .dic file is licensed under the ODbL 1.0; see DATA-LICENSE.md.",
];

/// The comment header of a lexicon file, with `extra` lines after the license note.
fn lexicon_header(extra: &[&str]) -> Vec<String> {
    let mut header: Vec<String> = DATA_NOTE.iter().map(|s| s.to_string()).collect();
    header.push(format!("Alar commit {}.", alar::ALAR_COMMIT));
    header.extend(extra.iter().map(|s| s.to_string()));
    header.push("Columns: stem, class, lemma, part of speech, tags.".to_string());
    header
}

#[derive(Parser)]
#[command(about = "Builds and measures the Kannada spelling dictionary and analyzer")]
struct Cli {
    #[command(subcommand)]
    command: Command,
}

#[derive(Subcommand)]
enum Command {
    /// Splits a Wikipedia XML dump on stdin into training and test word counts.
    Corpus {
        #[arg(long, default_value = "data/build")]
        out: PathBuf,
    },
    /// Builds the lexicon from Alar, the closed-class list and the training counts.
    Lexicon {
        #[arg(long, default_value = "data/raw/alar.yml")]
        alar: PathBuf,
        #[arg(long, default_value = "data/closed-class.tsv")]
        closed: PathBuf,
        #[arg(long, default_value = "data/build/wiki-train.tsv")]
        train: PathBuf,
        #[arg(long, default_value = "data/build/lexicon-alar.tsv")]
        out: PathBuf,
    },
    /// Adds stems induced from the training counts to a lexicon.
    Induce {
        #[arg(long, default_value = "data/build/lexicon-alar.tsv")]
        lexicon: PathBuf,
        #[arg(long, default_value = "data/build/wiki-train.tsv")]
        train: PathBuf,
        #[arg(long, default_value = "data/build/lexicon.tsv")]
        out: PathBuf,
    },
    /// Writes the Hunspell .aff and .dic files from the lexicon.
    Hunspell {
        #[arg(long, default_value = "data/build/lexicon.tsv")]
        lexicon: PathBuf,
        #[arg(long, default_value = "data/build/wiki-train.tsv")]
        train: PathBuf,
        #[arg(long, default_value = "dict/kn_IN")]
        out: PathBuf,
    },
    /// Prints every analysis of each word (arguments, or 1 per line on stdin).
    Analyze {
        /// The Hunspell dictionary, without the extension.
        #[arg(long, default_value = "dict/kn_IN")]
        dictionary: PathBuf,
        /// Also guess analyses of unknown words.
        #[arg(long)]
        guess: bool,
        words: Vec<String>,
    },
    /// Prints the lemma of each word.
    Stem {
        #[arg(long, default_value = "dict/kn_IN")]
        dictionary: PathBuf,
        words: Vec<String>,
    },
    /// Measures coverage and false acceptance on the held-out counts.
    Eval {
        #[arg(long, default_value = "dict/kn_IN")]
        dictionary: PathBuf,
        #[arg(long, default_value = "data/build/wiki-train.tsv")]
        train: PathBuf,
        #[arg(long, default_value = "data/build/wiki-test.tsv")]
        test: PathBuf,
        /// The dictionary whose accepted words are corrupted. Keep it fixed to compare dictionaries.
        #[arg(long, default_value = "dict/kn_IN-alar")]
        reference: PathBuf,
        /// Where to write the misspellings tried, for checking with Hunspell.
        #[arg(long, default_value = "data/build/misspellings.tsv")]
        misspellings: PathBuf,
        #[arg(long, default_value_t = 5000)]
        limit: usize,
    },
    /// Measures Hunspell's suggestions for misspellings that the dictionary rejects.
    Suggest {
        #[arg(long, default_value = "dict/kn_IN")]
        dictionary: PathBuf,
        #[arg(long, default_value = "data/build/misspellings.tsv")]
        misspellings: PathBuf,
        #[arg(long, default_value_t = 2000)]
        limit: usize,
    },
    /// Prints a deterministic sample of words built from the dictionary, and a typo of each,
    /// for checking that Hunspell and the analyzer agree.
    Sample {
        #[arg(long, default_value = "dict/kn_IN")]
        dictionary: PathBuf,
        /// How many dictionary stems to inflect.
        #[arg(long, default_value_t = 400)]
        stems: usize,
        /// How many forms of each stem to print.
        #[arg(long, default_value_t = 6)]
        forms: usize,
    },
    /// Prints the number of affix rules in each class.
    Rules,
}

fn main() -> Result<()> {
    match Cli::parse().command {
        Command::Corpus { out } => corpus(&out),
        Command::Lexicon {
            alar,
            closed,
            train,
            out,
        } => lexicon(&alar, &closed, &train, &out),
        Command::Induce {
            lexicon,
            train,
            out,
        } => induce(&lexicon, &train, &out),
        Command::Hunspell {
            lexicon,
            train,
            out,
        } => hunspell(&lexicon, &train, &out),
        Command::Analyze {
            dictionary,
            guess,
            words,
        } => analyze(&dictionary, guess, words),
        Command::Stem { dictionary, words } => stem(&dictionary, words),
        Command::Eval {
            dictionary,
            train,
            test,
            reference,
            misspellings,
            limit,
        } => evaluate(&dictionary, &reference, &train, &test, &misspellings, limit),
        Command::Suggest {
            dictionary,
            misspellings,
            limit,
        } => suggestions(&dictionary, &misspellings, limit),
        Command::Sample {
            dictionary,
            stems,
            forms,
        } => sample(&dictionary, stems, forms),
        Command::Rules => {
            for &class in ALL_CLASSES {
                println!("{}\t{:?}\t{}", class.flag(), class, rules_for(class).len());
            }
            Ok(())
        }
    }
}

fn load_lexicon(path: &Path) -> Result<Lexicon> {
    let text = fs::read_to_string(path).with_context(|| format!("reading {}", path.display()))?;
    Lexicon::parse(&text).map_err(anyhow::Error::msg)
}

/// The analyzer over a Hunspell dictionary written by `kspell hunspell`.
fn load_analyzer(dictionary: &Path) -> Result<Analyzer> {
    let path = dictionary.with_extension("dic");
    let text = fs::read_to_string(&path).with_context(|| format!("reading {}", path.display()))?;
    Ok(Analyzer::new(
        parse_dictionary(&text).map_err(anyhow::Error::msg)?,
    ))
}

/// Where the typo list goes, next to the confusion list: misspellings-alar.tsv gives typos-alar.tsv.
fn typo_path(misspellings: &Path) -> PathBuf {
    let name = misspellings
        .file_name()
        .and_then(|n| n.to_str())
        .unwrap_or("misspellings.tsv");
    misspellings.with_file_name(name.replacen("misspellings", "typos", 1))
}

fn corpus(out: &Path) -> Result<()> {
    let split = corpus::split_dump(io::stdin().lock())?;
    fs::create_dir_all(out)?;
    let note = |part: &str| {
        format!(
            "Kannada Wikipedia word counts ({part}, 1 article in {} held out). Text CC BY-SA 4.0.",
            corpus::TEST_EVERY
        )
    };
    split
        .train
        .save(&out.join("wiki-train.tsv"), &note("training"))?;
    split.test.save(&out.join("wiki-test.tsv"), &note("test"))?;
    println!(
        "{} articles; train {} tokens, {} types; test {} tokens, {} types",
        split.articles,
        split.train.tokens(),
        split.train.types(),
        split.test.tokens(),
        split.test.types()
    );
    Ok(())
}

fn lexicon(alar: &Path, closed: &Path, train: &Path, out: &Path) -> Result<()> {
    let entries = alar::load(alar)?;
    let built = build_lexicon::build(&entries, load_lexicon(closed)?, &Counts::load(train)?);
    let header = lexicon_header(&[]);
    let header: Vec<&str> = header.iter().map(String::as_str).collect();
    fs::write(out, built.lexicon.to_tsv(&header))?;
    println!(
        "{} Alar entries, {} headwords kept, {} lexicon entries",
        entries.len(),
        built.headwords,
        built.lexicon.len()
    );
    for (skip, n) in built.skipped {
        println!("  skipped {skip:?}: {n}");
    }
    Ok(())
}

fn induce(lexicon_path: &Path, train: &Path, out: &Path) -> Result<()> {
    let analyzer = Analyzer::new(load_lexicon(lexicon_path)?);
    let induced = induce::induce(&analyzer, &Counts::load(train)?);
    println!(
        "induced {} stems and {} whole words; left out {} likely misspellings",
        induced.stems.len(),
        induced.whole_words.len(),
        induced.likely_misspellings
    );
    let mut lexicon = Lexicon::from_entries(analyzer.lexicon().entries().into_iter().cloned());
    for e in induced.stems.into_iter().chain(induced.whole_words) {
        lexicon.insert(e);
    }
    let header = lexicon_header(&[
        "Also stems and words induced from Kannada Wikipedia word counts (kspell induce).",
    ]);
    let header: Vec<&str> = header.iter().map(String::as_str).collect();
    fs::write(out, lexicon.to_tsv(&header))?;
    Ok(())
}

fn hunspell(lexicon_path: &Path, train: &Path, out: &Path) -> Result<()> {
    let lexicon = load_lexicon(lexicon_path)?;
    let counts = Counts::load(train)?;
    let mut letters: std::collections::HashMap<char, u64> = std::collections::HashMap::new();
    for (word, n) in counts.sorted() {
        for c in word.chars() {
            *letters.entry(c).or_default() += n;
        }
    }
    let mut by_count: Vec<(char, u64)> = letters.into_iter().collect();
    by_count.sort_by(|a, b| b.1.cmp(&a.1).then(a.0.cmp(&b.0)));
    let try_chars: String = by_count.iter().map(|(c, _)| *c).collect();
    fs::write(
        out.with_extension("aff"),
        affix_file(&try_chars, AFFIX_NOTE),
    )?;
    fs::write(out.with_extension("dic"), dictionary_file(&lexicon))?;
    println!("wrote {}.aff and {}.dic", out.display(), out.display());
    Ok(())
}

fn suggestions(dictionary: &Path, misspellings: &Path, limit: usize) -> Result<()> {
    let analyzer = load_analyzer(dictionary)?;
    let text = fs::read_to_string(misspellings)?;
    let pairs: Vec<(String, String)> = text
        .lines()
        .filter(|l| !l.starts_with('#'))
        .filter_map(|l| l.split_once('\t'))
        .filter(|(_, bad)| !analyzer.accepts(bad))
        .take(limit)
        .map(|(good, bad)| (good.to_string(), bad.to_string()))
        .collect();
    let s = suggest::score(dictionary, &pairs)?;
    println!(
        "intended word suggested first: {:.1}%, in the top 5: {:.1}% ({} rejected misspellings)",
        percent(s.first as f64, s.tried as f64),
        percent(s.top5 as f64, s.tried as f64),
        s.tried
    );
    Ok(())
}

fn sample(dictionary: &Path, stems: usize, forms_per_stem: usize) -> Result<()> {
    let analyzer = load_analyzer(dictionary)?;
    let entries = analyzer.lexicon().entries();
    let step = (entries.len() / stems.max(1)).max(1);
    let mut rng = misspell::Rng::new(7);
    let mut out = io::stdout().lock();
    for entry in entries.iter().step_by(step) {
        let forms = entry.class.forms(&entry.stem);
        for _ in 0..forms_per_stem.min(forms.len()) {
            let word = &forms[rng.below(forms.len())].text;
            writeln!(out, "{word}")?;
            if let Some(typo) = misspell::typo(word, &mut rng) {
                writeln!(out, "{typo}")?;
            }
        }
    }
    Ok(())
}

fn input_words(words: Vec<String>) -> Result<Vec<String>> {
    if !words.is_empty() {
        return Ok(words);
    }
    io::stdin()
        .lock()
        .lines()
        .map(|l| Ok(l?.trim().to_string()))
        .filter(|w| !matches!(w, Ok(w) if w.is_empty()))
        .collect()
}

fn analyze(dictionary: &Path, guess: bool, words: Vec<String>) -> Result<()> {
    let analyzer = load_analyzer(dictionary)?;
    let mut out = io::stdout().lock();
    for word in input_words(words)? {
        let mut analyses = analyzer.analyze(&word);
        if analyses.is_empty() && guess {
            analyses = analyzer.guess(&word);
        }
        if analyses.is_empty() {
            writeln!(out, "{word}\t?")?;
        }
        for a in analyses {
            writeln!(out, "{word}\t{a}{}", if a.guessed { "\tguess" } else { "" })?;
        }
    }
    Ok(())
}

fn stem(dictionary: &Path, words: Vec<String>) -> Result<()> {
    let analyzer = load_analyzer(dictionary)?;
    let mut out = io::stdout().lock();
    for word in input_words(words)? {
        writeln!(out, "{word}\t{}", analyzer.stem(&word))?;
    }
    Ok(())
}

fn evaluate(
    dictionary: &Path,
    reference: &Path,
    train: &Path,
    test: &Path,
    misspellings: &Path,
    limit: usize,
) -> Result<()> {
    let analyzer = load_analyzer(dictionary)?;
    let reference = load_analyzer(reference)?;
    let (train, test) = (Counts::load(train)?, Counts::load(test)?);
    let c = coverage(&|w| analyzer.accepts(w), &test, 60);
    println!(
        "held-out tokens accepted: {:.1}% of {}",
        percent(c.accepted_tokens as f64, c.tokens as f64),
        c.tokens
    );
    println!(
        "held-out types accepted: {:.1}% of {}",
        percent(c.accepted_types as f64, c.types as f64),
        c.types
    );
    println!(
        "types seen {FREQUENT}+ times accepted: {:.1}% of {}",
        percent(c.accepted_frequent as f64, c.frequent_types as f64),
        c.frequent_types
    );
    let seen = |w: &str| train.contains(w) || test.contains(w);
    for (kind, corrupt, path) in [
        (
            "confusion",
            misspell::misspell as fn(&str, &mut misspell::Rng) -> Option<String>,
            misspellings.to_path_buf(),
        ),
        ("typo", misspell::typo, typo_path(misspellings)),
    ] {
        let source = |w: &str| reference.accepts(w);
        let f = false_acceptance(&analyzer, &source, &test, &seen, corrupt, limit, 2026);
        println!(
            "misspellings accepted ({kind}): {:.1}% of {} (1 edit each, never seen in the corpus)",
            percent(f.accepted as f64, f.tried as f64),
            f.tried
        );
        let mut list = String::from("# correct\tmisspelled\n");
        for (good, bad) in &f.samples {
            list.push_str(&format!("{good}\t{bad}\n"));
        }
        fs::write(path, list)?;
    }
    println!("most frequent rejected words:");
    for (w, n) in &c.top_rejected {
        println!("  {w}\t{n}");
    }
    Ok(())
}
